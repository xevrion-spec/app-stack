/**
 * Invoice PDF rendering with pdf-lib (pure JS, no native deps, runs in Workers). Standard Helvetica only,
 * so text is sanitised to WinAnsi. Content is data-only: no scripts, links or embedded files.
 */
import { PDFDocument, StandardFonts, rgb } from "pdf-lib";

export interface InvoicePdfInput {
  sellerName: string;
  vatNumber?: string | null;
  number: string;
  issueDate: string;
  dueDate: string;
  customerName: string;
  status: string;
  lines: { description: string; quantity: number; unitPence: number; vatRateCode: string }[];
  netPence: number;
  vatPence: number;
  grossPence: number;
}

const gbp = (p: number) => `${p < 0 ? "-" : ""}£${(Math.abs(p) / 100).toFixed(2).replace(/\B(?=(\d{3})+(?!\d))/g, ",")}`;
/** Keep printable WinAnsi-safe characters only (Helvetica cannot encode others). */
const pdfSafe = (s: string, max = 90) =>
  s
    .replace(/[\u2018\u2019]/g, "'")
    .replace(/[\u201C\u201D]/g, '"')
    .replace(/[\u2013\u2014]/g, "-")
    .replace(/[^\x20-\x7E£]/g, "?")
    .slice(0, max);

export async function renderInvoicePdf(inv: InvoicePdfInput): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  doc.setTitle(`Invoice ${pdfSafe(inv.number)}`);
  doc.setProducer("Xevrion Autopilot");
  doc.setCreator("Xevrion Autopilot");
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  let page = doc.addPage([595.28, 841.89]); // A4
  const ink = rgb(0.1, 0.12, 0.16),
    muted = rgb(0.4, 0.43, 0.48);
  let y = 790;
  const text = (s: string, x: number, size = 10, f = font, color = ink) => page.drawText(pdfSafe(s), { x, y, size, font: f, color });
  const right = (s: string, xr: number, size = 10, f = font) =>
    page.drawText(pdfSafe(s), { x: xr - f.widthOfTextAtSize(pdfSafe(s), size), y, size, font: f, color: ink });

  text(inv.sellerName, 50, 16, bold);
  right("INVOICE", 545, 16, bold);
  y -= 18;
  if (inv.vatNumber) text(`VAT reg. no. ${inv.vatNumber}`, 50, 9, font, muted);
  right(`No. ${inv.number}`, 545, 10);
  y -= 14;
  right(`Issued ${inv.issueDate}  ·  Due ${inv.dueDate}`.replace("·", "-"), 545, 9);
  y -= 34;
  text("Bill to", 50, 9, font, muted);
  y -= 14;
  text(inv.customerName, 50, 11, bold);
  if (inv.status === "draft") right("DRAFT", 545, 11, bold);
  y -= 34;
  const header = () => {
    text("Description", 50, 9, bold);
    right("Qty", 330, 9, bold);
    right("Unit", 400, 9, bold);
    right("VAT", 455, 9, bold);
    right("Net", 545, 9, bold);
    y -= 6;
    page.drawLine({ start: { x: 50, y }, end: { x: 545, y }, thickness: 0.5, color: muted });
    y -= 14;
  };
  header();
  for (const l of inv.lines) {
    if (y < 120) {
      page = doc.addPage([595.28, 841.89]);
      y = 790;
      header();
    }
    text(l.description, 50, 10);
    right(String(l.quantity), 330);
    right(gbp(l.unitPence), 400);
    right(l.vatRateCode, 455);
    right(gbp(Math.round(l.quantity * l.unitPence)), 545);
    y -= 16;
  }
  y -= 10;
  page.drawLine({ start: { x: 330, y: y + 8 }, end: { x: 545, y: y + 8 }, thickness: 0.5, color: muted });
  for (const [k, v, f] of [
    ["Net", inv.netPence, font],
    ["VAT", inv.vatPence, font],
    ["Total due", inv.grossPence, bold],
  ] as const) {
    right(k, 455, 10, f);
    right(gbp(v), 545, 10, f);
    y -= 16;
  }
  y = 60;
  text("Generated by Xevrion Autopilot. Please check details before sending.", 50, 8, font, muted);
  return doc.save();
}
